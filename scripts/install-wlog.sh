#!/usr/bin/env bash
# Employee installer for WienerLog.
#
# Usage (with curl pipe):
#   curl -fsSL https://wlog.wienerlabs.io/install.sh \
#     | WLOG_USER=kh0ra WLOG_EMAIL=you@wienerlabs.io WLOG_SERVER=wlog.wienerlabs.io bash
#
# Or with a local checkout:
#   WLOG_SOURCE_DIR=~/wienerlog ./scripts/install-wlog.sh
#
# Env vars:
#   WLOG_USER            (required) per-workspace handle, e.g. `kh0ra`
#   WLOG_EMAIL           (required) email shown in the user row
#   WLOG_SERVER          (default wlog.wienerlabs.io) host shared by all employees
#   WLOG_VERSION         (default v0.1.0) binary tag to install
#   WLOG_SOURCE_DIR      if set, cargo install from this checkout instead of downloading
#   WLOG_BIN             if set, treat this path as the wlog binary (skip download)
#   WLOG_PREFIX          (default /usr/local) install prefix; binary lands in $WLOG_PREFIX/bin
#   WLOG_REPLICA_URL     (required for `wlog ls/show/daily`) read-only Postgres URL
#   WLOG_SKIP_HOOKS      if 1, do not run `wlog hooks install`
#   WLOG_SKIP_DAEMON     if 1, do not install the launchd / systemd unit

set -euo pipefail

# ---------------------------------------------------------------- helpers

bold()  { printf "\033[1m%s\033[0m\n" "$*"; }
warn()  { printf "\033[33m%s\033[0m\n" "$*" >&2; }
die()   { printf "\033[31merror:\033[0m %s\n" "$*" >&2; exit 1; }

require() {
    local var="$1"
    if [[ -z "${!var:-}" ]]; then
        die "$var is required (e.g. export $var=...)"
    fi
}

# ---------------------------------------------------------------- env

require WLOG_USER
require WLOG_EMAIL

: "${WLOG_SERVER:=wlog.wienerlabs.io}"
: "${WLOG_VERSION:=v0.1.0}"
: "${WLOG_PREFIX:=/usr/local}"
: "${WLOG_REPLICA_URL:=}"
: "${WLOG_SKIP_HOOKS:=0}"
: "${WLOG_SKIP_DAEMON:=0}"

case "$(uname -s)" in
    Darwin)  os="macos";  daemon_kind="launchd" ;;
    Linux)   os="linux";  daemon_kind="systemd" ;;
    *)       die "unsupported OS $(uname -s); use macOS or Linux" ;;
esac

arch="$(uname -m)"
case "$arch" in
    arm64|aarch64) arch="arm64" ;;
    x86_64|amd64)  arch="amd64" ;;
    *)             die "unsupported arch $arch" ;;
esac

bold "==> Installing wlog for $WLOG_USER ($os/$arch)"

# ---------------------------------------------------------------- binary

bin_path="$WLOG_PREFIX/bin/wlog"

install_binary() {
    if [[ -n "${WLOG_BIN:-}" && -x "$WLOG_BIN" ]]; then
        bold "==> Using preinstalled binary $WLOG_BIN"
        sudo install -m 0755 "$WLOG_BIN" "$bin_path"
        return
    fi

    if [[ -n "${WLOG_SOURCE_DIR:-}" && -d "$WLOG_SOURCE_DIR" ]]; then
        bold "==> Building from source $WLOG_SOURCE_DIR"
        ( cd "$WLOG_SOURCE_DIR" && cargo build --release -p wlog-cli )
        sudo install -m 0755 "$WLOG_SOURCE_DIR/target/release/wlog" "$bin_path"
        return
    fi

    bold "==> Downloading wlog $WLOG_VERSION for $os/$arch"
    tmp="$(mktemp -d)"
    trap 'rm -rf "$tmp"' EXIT
    url="https://$WLOG_SERVER/dl/$os/$arch/wlog-$WLOG_VERSION"
    if ! curl -fsSL "$url" -o "$tmp/wlog"; then
        die "download failed: $url
hint: set WLOG_SOURCE_DIR=~/wienerlog if you have a checkout"
    fi
    chmod +x "$tmp/wlog"
    sudo install -m 0755 "$tmp/wlog" "$bin_path"
}

install_binary
"$bin_path" --version

# ---------------------------------------------------------------- config

config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/wlog"
mkdir -p "$config_dir"
config_path="$config_dir/wlog.toml"

if [[ -f "$config_path" ]]; then
    warn "config exists at $config_path; leaving it alone"
else
    bold "==> Writing $config_path"
    cat > "$config_path" <<EOF
# Generated by scripts/install-wlog.sh on $(date -u +%Y-%m-%dT%H:%MZ)
[workspace]
slug = "$WLOG_USER"
name = "$WLOG_USER"
user = "$WLOG_USER"

[storage]
url = "${WLOG_REPLICA_URL:-postgres://reader@$WLOG_SERVER:5435/wlog}"
max_connections = 4
EOF
fi

# ---------------------------------------------------------------- daemon unit

install_launchd() {
    plist="$HOME/Library/LaunchAgents/io.wienerlabs.wlog-daemon.plist"
    mkdir -p "$(dirname "$plist")"
    cat > "$plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>io.wienerlabs.wlog-daemon</string>
    <key>ProgramArguments</key>
    <array>
        <string>$bin_path</string>
        <string>daemon</string>
        <string>run</string>
        <string>--cc-projects-dir</string>
        <string>auto</string>
        <string>--nats-url</string>
        <string>nats://$WLOG_SERVER:4222</string>
    </array>
    <key>EnvironmentVariables</key>
    <dict>
        <key>WLOG_DAEMON_WORKSPACE</key>
        <string>$WLOG_USER</string>
        <key>RUST_LOG</key>
        <string>info</string>
    </dict>
    <key>RunAtLoad</key><true/>
    <key>KeepAlive</key><true/>
    <key>ThrottleInterval</key><integer>10</integer>
    <key>StandardOutPath</key><string>$HOME/Library/Logs/wlog-daemon.out.log</string>
    <key>StandardErrorPath</key><string>$HOME/Library/Logs/wlog-daemon.err.log</string>
</dict>
</plist>
EOF
    mkdir -p "$HOME/Library/Logs"
    launchctl bootout "gui/$(id -u)/io.wienerlabs.wlog-daemon" 2>/dev/null || true
    launchctl bootstrap "gui/$(id -u)" "$plist"
    launchctl enable "gui/$(id -u)/io.wienerlabs.wlog-daemon"
}

install_systemd_user() {
    unit_dir="$HOME/.config/systemd/user"
    mkdir -p "$unit_dir"
    cat > "$unit_dir/wlog-daemon.service" <<EOF
[Unit]
Description=WienerLog daemon
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=$bin_path daemon run --cc-projects-dir auto --nats-url nats://$WLOG_SERVER:4222
Environment=WLOG_DAEMON_WORKSPACE=$WLOG_USER
Environment=RUST_LOG=info
Restart=always
RestartSec=10

[Install]
WantedBy=default.target
EOF
    systemctl --user daemon-reload
    systemctl --user enable --now wlog-daemon.service
}

if [[ "$WLOG_SKIP_DAEMON" != "1" ]]; then
    bold "==> Installing daemon unit ($daemon_kind)"
    case "$daemon_kind" in
        launchd) install_launchd ;;
        systemd) install_systemd_user ;;
    esac
else
    warn "WLOG_SKIP_DAEMON=1; daemon unit was not installed"
fi

# ---------------------------------------------------------------- hooks

if [[ "$WLOG_SKIP_HOOKS" != "1" ]]; then
    if git rev-parse --show-toplevel >/dev/null 2>&1; then
        repo="$(git rev-parse --show-toplevel)"
        bold "==> Installing git hooks in $repo"
        "$bin_path" hooks install --repo "$repo"
    else
        warn "not inside a git repo; skipping hook install. Run from each repo: wlog hooks install"
    fi
fi

# ---------------------------------------------------------------- verify

bold "==> Verifying with wlog status"
sleep 1
"$bin_path" status --no-db || warn "wlog status reported issues; review hints above"

bold "==> Done."
echo
echo "Next:"
echo "  - wlog daily        (see proposed tasks; will be empty on day 1)"
echo "  - wlog ls           (list everything)"
echo "  - wlog hooks install (in every repo you want observed)"
echo
echo "Onboarding doc: https://github.com/wienerlabs/wienerlog/blob/main/docs/onboarding.md"
