//! Git ingestion library.
//!
//! Phase 1 scope: install, uninstall, and status of repository hooks that
//! emit JSON events to a local socket. The daemon side (socket reader +
//! NATS publisher) lands in the same phase as a separate module.
//!
//! Hook scripts are tiny: they shell out to `wlog hooks notify <kind>`
//! which publishes a JSON envelope to `${XDG_RUNTIME_DIR}/wlog.sock`.
//! The script carries a header comment identifying the wlog version that
//! wrote it so that `uninstall` can refuse to remove third-party hooks.

#![warn(missing_docs)]

use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

use thiserror::Error;

/// Crate version, surfaced in logs and in the hook script header.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// Header line written at the top of every wlog-managed hook. The line
/// must be exactly this string (modulo trailing whitespace) for
/// `uninstall` to consider the hook safe to remove.
pub const HOOK_HEADER_PREFIX: &str = "# wlog-managed hook v";

/// The hooks that `wlog hooks install` writes.
///
/// Adding a variant requires bumping the hook script version in the
/// header and updating the install routine to write the new file.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum HookKind {
    /// Fires after every commit.
    PostCommit,
    /// Fires after every merge.
    PostMerge,
    /// Fires before push, useful for capturing remote URL.
    PrePush,
}

impl HookKind {
    /// Iterate over every managed hook kind.
    pub const ALL: &'static [Self] = &[Self::PostCommit, Self::PostMerge, Self::PrePush];

    /// Filename inside `.git/hooks/`.
    pub const fn filename(self) -> &'static str {
        match self {
            Self::PostCommit => "post-commit",
            Self::PostMerge => "post-merge",
            Self::PrePush => "pre-push",
        }
    }

    /// Wire-format identifier passed to `wlog hooks notify`.
    pub const fn wire(self) -> &'static str {
        self.filename()
    }
}

/// Errors raised by the hook installer.
#[derive(Debug, Error)]
pub enum HookError {
    /// Repository does not look like a git checkout.
    #[error("not a git repository: {0}")]
    NotARepo(PathBuf),
    /// Existing hook was not written by wlog; refuse to overwrite without
    /// `force`.
    #[error("hook {0} exists and is not wlog-managed (pass force to overwrite)")]
    Foreign(PathBuf),
    /// Filesystem error.
    #[error("io error: {0}")]
    Io(#[from] std::io::Error),
}

/// Outcome of a single install or uninstall operation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum HookAction {
    /// Hook was created.
    Installed,
    /// Hook already up to date.
    Unchanged,
    /// Hook was overwritten because `force` was true.
    Overwritten,
    /// Hook was removed.
    Removed,
    /// Nothing to do (uninstall on a missing or foreign hook).
    Skipped,
}

/// Report returned by `install_all` and `uninstall_all`.
#[derive(Debug, Clone)]
pub struct HookReport {
    /// Per-hook outcomes.
    pub entries: Vec<(HookKind, HookAction)>,
}

/// Locate the `.git/hooks` directory for `repo_path`.
pub fn hooks_dir(repo_path: &Path) -> Result<PathBuf, HookError> {
    let git_dir = repo_path.join(".git");
    if !git_dir.exists() {
        return Err(HookError::NotARepo(repo_path.to_path_buf()));
    }
    // Submodules and worktrees use a `.git` file pointing to the real dir.
    if git_dir.is_file() {
        let pointer = fs::read_to_string(&git_dir)?;
        let line = pointer
            .lines()
            .find_map(|l| l.strip_prefix("gitdir: "))
            .ok_or_else(|| HookError::NotARepo(repo_path.to_path_buf()))?;
        return Ok(PathBuf::from(line.trim()).join("hooks"));
    }
    Ok(git_dir.join("hooks"))
}

/// Render the hook script body for a given kind.
pub fn render_script(kind: HookKind) -> String {
    let wire = kind.wire();
    format!(
        "#!/usr/bin/env bash\n\
         {HOOK_HEADER_PREFIX}{VERSION}\n\
         # Auto-generated by wlog hooks install. Edits are overwritten on\n\
         # re-install. Remove the header line to detach this hook from wlog.\n\
         set -eu\n\
         # Detach if the repo opted out via .wlog/no-track.\n\
         if [ -f .wlog/no-track ]; then exit 0; fi\n\
         # Best effort: never block the commit if wlog or the socket are\n\
         # unavailable.\n\
         if command -v wlog >/dev/null 2>&1; then\n\
         \twlog hooks notify {wire} \"$@\" >/dev/null 2>&1 &\n\
         fi\n"
    )
}

/// Install all managed hooks into `repo_path`.
pub fn install_all(repo_path: &Path, force: bool) -> Result<HookReport, HookError> {
    let dir = hooks_dir(repo_path)?;
    fs::create_dir_all(&dir)?;
    let mut entries = Vec::new();
    for kind in HookKind::ALL.iter().copied() {
        entries.push((kind, install_one(&dir, kind, force)?));
    }
    Ok(HookReport { entries })
}

/// Uninstall all wlog-managed hooks from `repo_path`. Foreign hooks are
/// left in place untouched.
pub fn uninstall_all(repo_path: &Path) -> Result<HookReport, HookError> {
    let dir = hooks_dir(repo_path)?;
    let mut entries = Vec::new();
    for kind in HookKind::ALL.iter().copied() {
        entries.push((kind, uninstall_one(&dir, kind)?));
    }
    Ok(HookReport { entries })
}

/// Report which hooks are currently managed by wlog.
pub fn status(repo_path: &Path) -> Result<HookReport, HookError> {
    let dir = hooks_dir(repo_path)?;
    let mut entries = Vec::new();
    for kind in HookKind::ALL.iter().copied() {
        let path = dir.join(kind.filename());
        let action = if !path.exists() {
            HookAction::Skipped
        } else if is_wlog_managed(&path)? {
            HookAction::Installed
        } else {
            // Foreign hook; report as Unchanged so that human reads
            // "exists, not ours".
            HookAction::Unchanged
        };
        entries.push((kind, action));
    }
    Ok(HookReport { entries })
}

fn install_one(dir: &Path, kind: HookKind, force: bool) -> Result<HookAction, HookError> {
    let path = dir.join(kind.filename());
    let body = render_script(kind);
    if path.exists() {
        if is_wlog_managed(&path)? {
            // Re-installing an existing wlog hook.
            let existing = fs::read_to_string(&path)?;
            if existing == body {
                return Ok(HookAction::Unchanged);
            }
            write_executable(&path, &body)?;
            return Ok(HookAction::Overwritten);
        }
        if !force {
            return Err(HookError::Foreign(path));
        }
        write_executable(&path, &body)?;
        return Ok(HookAction::Overwritten);
    }
    write_executable(&path, &body)?;
    Ok(HookAction::Installed)
}

fn uninstall_one(dir: &Path, kind: HookKind) -> Result<HookAction, HookError> {
    let path = dir.join(kind.filename());
    if !path.exists() {
        return Ok(HookAction::Skipped);
    }
    if !is_wlog_managed(&path)? {
        return Ok(HookAction::Skipped);
    }
    fs::remove_file(&path)?;
    Ok(HookAction::Removed)
}

fn is_wlog_managed(path: &Path) -> Result<bool, HookError> {
    let body = fs::read_to_string(path)?;
    Ok(body.lines().any(|l| l.starts_with(HOOK_HEADER_PREFIX)))
}

fn write_executable(path: &Path, body: &str) -> Result<(), HookError> {
    {
        let mut f = fs::File::create(path)?;
        f.write_all(body.as_bytes())?;
        f.sync_all()?;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = fs::metadata(path)?.permissions();
        perms.set_mode(0o755);
        fs::set_permissions(path, perms)?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::process::Command;

    fn temp_repo() -> tempdir::TempDir {
        let tmp = tempdir::TempDir::new("wlog-hooks").expect("tempdir");
        Command::new("git")
            .arg("init")
            .arg("-q")
            .arg(tmp.path())
            .status()
            .expect("git init");
        tmp
    }

    #[test]
    fn install_writes_three_hooks() {
        let tmp = temp_repo();
        let report = install_all(tmp.path(), false).expect("install");
        assert_eq!(report.entries.len(), 3);
        for (_, action) in &report.entries {
            assert_eq!(action, &HookAction::Installed);
        }
        for kind in HookKind::ALL.iter().copied() {
            let p = tmp.path().join(".git").join("hooks").join(kind.filename());
            assert!(p.exists(), "expected hook {}", p.display());
            let body = fs::read_to_string(&p).unwrap();
            assert!(body.contains(HOOK_HEADER_PREFIX));
        }
    }

    #[test]
    fn reinstall_is_idempotent() {
        let tmp = temp_repo();
        install_all(tmp.path(), false).expect("install 1");
        let second = install_all(tmp.path(), false).expect("install 2");
        for (_, action) in &second.entries {
            assert_eq!(action, &HookAction::Unchanged);
        }
    }

    #[test]
    fn uninstall_removes_only_managed_hooks() {
        let tmp = temp_repo();
        // Drop a foreign hook in.
        let dir = tmp.path().join(".git").join("hooks");
        fs::create_dir_all(&dir).unwrap();
        let foreign = dir.join("post-commit");
        fs::write(&foreign, "#!/bin/sh\necho foreign\n").unwrap();
        // Installing without force must refuse.
        let err = install_all(tmp.path(), false).unwrap_err();
        assert!(matches!(err, HookError::Foreign(_)));
        // Forced install overwrites.
        let r = install_all(tmp.path(), true).expect("forced install");
        assert!(matches!(
            r.entries
                .iter()
                .find(|(k, _)| *k == HookKind::PostCommit)
                .unwrap()
                .1,
            HookAction::Overwritten
        ));
        // Uninstall removes the wlog ones.
        let r = uninstall_all(tmp.path()).expect("uninstall");
        for (_, action) in &r.entries {
            assert_eq!(action, &HookAction::Removed);
        }
    }
}
